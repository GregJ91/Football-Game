import type { ClubColours } from '../engine/types';

/**
 * Real club names, colours and grounds (fictional players). Each list is in
 * rough order of strength, best first, and is used when "Real club names"
 * is chosen for a new game. Line-ups follow the 2025/26 season; the lower
 * non-league divisions are a close approximation of the real leagues.
 *
 * Format: 'Name|SHT|primary|secondary|pattern|Stadium|capacity', where the
 * pattern is p(lain), s(tripes), h(oops), v (halves) or x (sash), and the
 * stadium and capacity are optional.
 */
export interface RealClub {
  name: string;
  shortName: string;
  colours: ClubColours;
  stadium?: string;
  capacity?: number;
}

const PATTERN = { p: 'plain', s: 'stripes', h: 'hoops', v: 'halves', x: 'sash' } as const;

export function parseRealClub(line: string): RealClub {
  const [name, shortName, primary, secondary, pattern, stadium, capacity] = line.split('|');
  return {
    name,
    shortName,
    colours: { primary, secondary, pattern: PATTERN[(pattern || 'p') as keyof typeof PATTERN] },
    stadium: stadium || undefined,
    capacity: capacity ? Number(capacity) : undefined,
  };
}

